import { BacklinkItem } from '../types/seo';

/**
 * Generates and downloads a standard Google Search Console disavow.txt file.
 * Lines beginning with # are comments.
 * domain:example.com disavows all links from that domain.
 * Full URLs disavow specific links.
 */
export function exportGoogleDisavowFile(domain: string, backlinks: BacklinkItem[]): void {
  const disavowedItems = backlinks.filter(
    b => b.disavowStatus === 'disavow-domain' || b.disavowStatus === 'disavow-link'
  );

  if (disavowedItems.length === 0) {
    alert('No backlinks have been marked for disavow. Mark links as "Disavow Link" or "Disavow Domain" first.');
    return;
  }

  const lines: string[] = [
    `# Google Search Console Disavow File for ${domain}`,
    `# Generated by Razza Metrics on ${new Date().toISOString()}`,
    '# Offline manual selection only. Nothing has been submitted to Google.',
    '# A heuristic risk score alone is not a reason to disavow.',
    ''
  ];

  const processedDomains = new Set<string>();

  disavowedItems.forEach(item => {
    if (item.disavowStatus === 'disavow-domain') {
      try {
        const urlObj = new URL(item.sourceUrl || 'https://' + item.sourceDomain);
        const host = urlObj.hostname.replace(/^www\./, '');
        if (!processedDomains.has(host)) {
          processedDomains.add(host);
          lines.push('# Domain explicitly selected for manual review');
          lines.push(`domain:${host}`);
        }
      } catch { /* Unknown domains cannot be exported as disavow targets. */ }
    } else if (item.disavowStatus === 'disavow-link' && item.sourceUrl) {
      lines.push('# URL explicitly selected for manual review');
      lines.push(item.sourceUrl);
    }
  });

  const content = lines.join('\r\n');
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `disavow-${domain.replace(/[^a-zA-Z0-9.-]/g, '_')}.txt`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
